export function getScene(lang: Language, lesson: LessonId, route: BoundaryRoute = 'native') {
  const id = sceneIdFor(lesson, route),
    layout = sceneLayouts[id],
    languageIndex = lang === 'zh' ? 0 : 1;
  return {
    id,
    nodes: layout.nodes.map((position) => {
      const copy = modules[position.id],
        [name, role, detail, ...facts] = copy[lang];
      return {
        ...position,
        name,
        role,
        detail,
        facts,
        english: copy.english,
        code: copy.code,
        file: copy.file,
        color: colors[position.glyph] ?? '#dfe9d8',
      };
    }),
    edges: layout.edges.map((flow) => ({ ...flow, text: edgeLabels[id][flow.id][languageIndex] })),
    zones: layout.zones?.map((zone) => ({ ...zone, text: zones[zone.id][languageIndex] })),
  };
}
export type Scene = ReturnType<typeof getScene>;
